"""Evaluation and reporting tools.

This module provides tools for generating final evaluation reports
and dashboard data from interview results.
"""

import json
import logging
from datetime import datetime, timezone
from typing import Dict, List

from langchain_core.tools import tool

logger = logging.getLogger(__name__)


@tool
def generate_final_report(
    candidate_name: str,
    role: str,
    rubric_json: str,
    citations_json: str,
    trust_score: float,
    summary_notes: str,
) -> str:
    """
    Generate a final evaluation report in Markdown format.

    Args:
        candidate_name: Name of the candidate.
        role: The role being interviewed for.
        rubric_json: Filled rubric as JSON.
        citations_json: Citations array as JSON.
        trust_score: Overall trust score (0-1).
        summary_notes: Additional notes from the interviewer.

    Returns:
        Markdown formatted final report.
    """
    try:
        # Parse inputs
        try:
            rubric = json.loads(rubric_json)
        except json.JSONDecodeError:
            rubric = {"error": "Invalid rubric JSON"}

        try:
            citations = json.loads(citations_json) if citations_json else []
        except json.JSONDecodeError:
            citations = []

        # Calculate rubric totals
        dimensions = rubric.get("dimensions", [])
        total_score = 0
        max_score = 0
        scored_dimensions = []

        for dim in dimensions:
            max_score += dim.get("max_score", 5)
            if dim.get("score") is not None:
                total_score += dim["score"]
                scored_dimensions.append(dim)

        percentage = (total_score / max_score * 100) if max_score > 0 else 0

        # Determine recommendation
        if percentage >= 80 and trust_score >= 0.7:
            recommendation = "Strong Yes ✓✓"
        elif percentage >= 65 and trust_score >= 0.5:
            recommendation = "Yes ✓"
        elif percentage >= 50:
            recommendation = "Maybe ○"
        elif percentage >= 35:
            recommendation = "No ✗"
        else:
            recommendation = "Strong No ✗✗"

        # Build the report
        report_lines = [
            "# Interview Evaluation Report",
            "",
            f"**Candidate:** {candidate_name}",
            f"**Role:** {role}",
            f"**Date:** {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}",
            "",
            "---",
            "",
            "## Overall Assessment",
            "",
            "| Metric | Value |",
            "|--------|-------|",
            f"| **Overall Score** | {total_score}/{max_score} ({percentage:.1f}%) |",
            f"| **Trust Score** | {trust_score:.0%} |",
            f"| **Recommendation** | {recommendation} |",
            "",
            "---",
            "",
            "## Rubric Scores",
            "",
            "| Dimension | Score | Reasoning |",
            "|-----------|-------|-----------|",
        ]

        for dim in scored_dimensions:
            score = dim.get("score", "-")
            max_s = dim.get("max_score", 5)
            reasoning = dim.get("reasoning", "No reasoning provided")
            # Truncate long reasoning for table
            reasoning_short = reasoning[:100] + "..." if len(reasoning) > 100 else reasoning
            report_lines.append(
                f"| {dim.get('name', 'Unknown')} | {score}/{max_s} | {reasoning_short} |"
            )

        report_lines.extend(
            [
                "",
                "---",
                "",
                "## Trust & Verification",
                "",
                f"**Trust Score:** {trust_score:.0%}",
                "",
            ]
        )

        # Add citations summary
        if citations:
            verified = sum(1 for c in citations if c.get("verdict") == "verified")
            unverified = sum(1 for c in citations if c.get("verdict") == "unverified")
            contradiction = sum(1 for c in citations if c.get("verdict") == "contradiction")

            report_lines.extend(
                [
                    f"**Claims Verified:** {verified} of {len(citations)}",
                    f"- Verified: {verified}",
                    f"- Unverified: {unverified}",
                    f"- Contradictions: {contradiction}",
                    "",
                ]
            )

        report_lines.extend(
            [
                "---",
                "",
                "## Summary Notes",
                "",
                summary_notes if summary_notes else "_No additional notes provided._",
                "",
                "---",
                "",
                "*Report generated by HASHLive Interview System*",
            ]
        )

        return "\n".join(report_lines)

    except Exception as e:
        logger.exception(f"Error generating final report: {e}")
        return f"Error generating report: {str(e)}"


@tool
def get_dashboard_data(rubric_json: str, trust_score: float, speech_confidence: float) -> str:
    """
    Generate data formatted for dashboard charts.

    Args:
        rubric_json: Filled rubric as JSON.
        trust_score: Trust score (0-1).
        speech_confidence: Speech confidence score (0-1).

    Returns:
        JSON with chart-ready data (labels, values, colors).
    """
    try:
        try:
            rubric = json.loads(rubric_json)
        except json.JSONDecodeError:
            return json.dumps({"error": "Invalid rubric JSON"})

        dimensions = rubric.get("dimensions", [])

        # Rubric spider/radar chart data
        rubric_chart = {
            "type": "radar",
            "labels": [],
            "values": [],
            "max_values": [],
        }

        for dim in dimensions:
            rubric_chart["labels"].append(dim.get("name", "Unknown"))
            rubric_chart["values"].append(dim.get("score") or 0)
            rubric_chart["max_values"].append(dim.get("max_score", 5))

        # Overall scores bar chart
        scores_chart = {
            "type": "bar",
            "labels": ["Trust Score", "Speech Confidence", "Rubric Score"],
            "values": [
                round(trust_score * 100, 1),
                round(speech_confidence * 100, 1),
                calculate_rubric_percentage(dimensions),
            ],
            "colors": [
                get_score_color(trust_score),
                get_score_color(speech_confidence),
                get_score_color(calculate_rubric_percentage(dimensions) / 100),
            ],
        }

        # Summary metrics
        total_score = sum(d.get("score", 0) or 0 for d in dimensions)
        max_score = sum(d.get("max_score", 5) for d in dimensions)

        summary = {
            "overall_percentage": round(total_score / max_score * 100, 1) if max_score > 0 else 0,
            "trust_score": round(trust_score * 100, 1),
            "speech_confidence": round(speech_confidence * 100, 1),
            "dimensions_scored": sum(1 for d in dimensions if d.get("score") is not None),
            "dimensions_total": len(dimensions),
        }

        result = {
            "rubric_chart": rubric_chart,
            "scores_chart": scores_chart,
            "summary": summary,
        }

        return json.dumps(result, indent=2)

    except Exception as e:
        logger.exception(f"Error generating dashboard data: {e}")
        return json.dumps({"error": f"Failed to generate dashboard data: {str(e)}"})


@tool
def generate_candidate_ranking_entry(
    candidate_id: str,
    candidate_name: str,
    role: str,
    rubric_json: str,
    trust_score: float,
    speech_confidence: float,
) -> str:
    """
    Generate a ranking entry for a candidate suitable for dashboard ranking list.

    Args:
        candidate_id: Unique ID of the candidate.
        candidate_name: Name of the candidate.
        role: Role being interviewed for.
        rubric_json: Filled rubric as JSON.
        trust_score: Trust score (0-1).
        speech_confidence: Speech confidence score (0-1).

    Returns:
        JSON with ranking entry data.
    """
    try:
        try:
            rubric = json.loads(rubric_json)
        except json.JSONDecodeError:
            return json.dumps({"error": "Invalid rubric JSON"})

        dimensions = rubric.get("dimensions", [])

        # Calculate composite score
        rubric_pct = calculate_rubric_percentage(dimensions) / 100
        composite_score = (
            rubric_pct * 0.5  # 50% weight on rubric
            + trust_score * 0.35  # 35% weight on trust
            + speech_confidence * 0.15  # 15% weight on speech
        )

        # Determine status
        if composite_score >= 0.75:
            status = "recommended"
        elif composite_score >= 0.5:
            status = "consider"
        else:
            status = "not_recommended"

        result = {
            "candidate_id": candidate_id,
            "candidate_name": candidate_name,
            "role": role,
            "composite_score": round(composite_score * 100, 1),
            "rubric_score": round(rubric_pct * 100, 1),
            "trust_score": round(trust_score * 100, 1),
            "speech_confidence": round(speech_confidence * 100, 1),
            "status": status,
            "evaluated_at": datetime.now(timezone.utc).isoformat(),
        }

        return json.dumps(result, indent=2)

    except Exception as e:
        logger.exception(f"Error generating ranking entry: {e}")
        return json.dumps({"error": f"Failed to generate ranking entry: {str(e)}"})


def calculate_rubric_percentage(dimensions: List[Dict]) -> float:
    """Calculate rubric percentage from dimensions."""
    total = sum(d.get("score", 0) or 0 for d in dimensions)
    max_total = sum(d.get("max_score", 5) for d in dimensions)
    return (total / max_total * 100) if max_total > 0 else 0


def get_score_color(score: float) -> str:
    """Get color for score visualization."""
    if score >= 0.75:
        return "#22c55e"  # Green
    elif score >= 0.5:
        return "#eab308"  # Yellow
    else:
        return "#ef4444"  # Red
